#!/usr/bin/env python3
"""Convert a TPS25751 patch bundle binary into a C++ header.

Usage: scripts/bin_to_header.py <lowRegion.bin> [-o <header>] [--name <identifier>]
                                [--max-size <bytes>]

The input is the low-region binary that TI's Application Customization Tool
exports (a patch bundle: firmware patch plus register configuration). The
output defines

    const uint8_t <name>[] = { ... };
    constexpr size_t <name>_size = sizeof(<name>);

and a comment block with the source file name, the size, the SHA-256, and the
version word. examples/eeprom-update includes the result as src/patch_bundle.h;
the default name is the one that example uses:

    scripts/bin_to_header.py <build>_lowRegion.bin \\
        -o examples/eeprom-update/src/patch_bundle.h

Without -o the header goes to standard output.

The input must be a patch bundle, checked the way
TPS25751EepromUpdater::checkImage() checks it: it starts with Header_ID
0xACE00001 (little-endian), is at least 0x38 bytes long, and is no longer than
one EEPROM region (0x3C00 bytes on a 32 KB part; --max-size changes the limit).
A file that fails a check is rejected and no header is written, so a full-flash
image or a wrong file cannot be embedded by mistake.

Exits 0 on success, 1 if the input cannot be read or is rejected.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

HEADER_ID = 0xACE00001          # first word of every patch bundle (SLVAFL1, Boot Process)
MIN_SIZE = 0x38                 # header through the version word
VERSION_OFFSET = 0x34           # word that matches the VERSION register (0x0F)
DEFAULT_MAX_SIZE = 0x3C00       # one region of a 32768-byte EEPROM
DEFAULT_NAME = "tps25751_eeprom_bundle"
DEFAULT_FILE_NAME = "patch_bundle.h"
BYTES_PER_LINE = 16

_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")


def check_bundle(data: bytes, max_size: int = DEFAULT_MAX_SIZE) -> None:
    """Raise ValueError unless `data` is a patch bundle of an acceptable size."""
    if len(data) < MIN_SIZE:
        raise ValueError(f"{len(data)} bytes is shorter than the {MIN_SIZE}-byte minimum for a patch bundle")
    if len(data) > max_size:
        raise ValueError(f"{len(data)} bytes is longer than the {max_size}-byte limit (one EEPROM region)")
    header = int.from_bytes(data[0:4], "little")
    if header != HEADER_ID:
        raise ValueError(f"first word is 0x{header:08X}, not Header_ID 0x{HEADER_ID:08X}; not a patch bundle")


def version_word(data: bytes) -> int:
    """The little-endian word at image offset 0x34."""
    return int.from_bytes(data[VERSION_OFFSET:VERSION_OFFSET + 4], "little")


def render(data: bytes, name: str = DEFAULT_NAME, source: str = "",
           file_name: str = DEFAULT_FILE_NAME) -> str:
    """Return the header text for `data`. Does not check the bundle."""
    if not _IDENTIFIER.match(name):
        raise ValueError(f"'{name}' is not a C++ identifier")

    rows = []
    for offset in range(0, len(data), BYTES_PER_LINE):
        chunk = data[offset:offset + BYTES_PER_LINE]
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in chunk))
    body = ",\n".join(rows)

    return f"""#pragma once

/**
 * @file {file_name}
 * @brief TPS25751 patch bundle for the eeprom-update example
 *
 * Generated by scripts/bin_to_header.py. Do not edit it; generate it again.
 *
 *   Source file:  {source or "(not recorded)"}
 *   Size:         {len(data)} bytes
 *   SHA-256:      {hashlib.sha256(data).hexdigest()}
 *   Version word: 0x{version_word(data):08X} (image offset 0x{VERSION_OFFSET:02X}; matches the VERSION register, 0x0F)
 */

#include <stddef.h>
#include <stdint.h>

/// Patch bundle bytes: a low-region binary from TI's Application Customization Tool.
const uint8_t {name}[] = {{
{body}
}};

/// Number of bytes in {name}.
constexpr size_t {name}_size = sizeof({name});
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Convert a TPS25751 patch bundle binary into a C++ header.")
    parser.add_argument("input", type=Path, help="low-region binary (.bin)")
    parser.add_argument("-o", "--output", type=Path, help="header to write (default: standard output)")
    parser.add_argument("--name", default=DEFAULT_NAME,
                        help=f"array identifier (default: {DEFAULT_NAME})")
    parser.add_argument("--max-size", type=lambda v: int(v, 0), default=DEFAULT_MAX_SIZE,
                        help=f"largest accepted size in bytes (default: 0x{DEFAULT_MAX_SIZE:X})")
    args = parser.parse_args(argv)

    try:
        data = args.input.read_bytes()
    except OSError as error:
        print(f"bin_to_header: cannot read {args.input}: {error.strerror}", file=sys.stderr)
        return 1

    try:
        check_bundle(data, args.max_size)
        text = render(data, args.name, args.input.name,
                      args.output.name if args.output else DEFAULT_FILE_NAME)
    except ValueError as error:
        print(f"bin_to_header: {args.input.name}: {error}", file=sys.stderr)
        return 1

    if args.output is None:
        sys.stdout.write(text)
        return 0

    try:
        args.output.write_text(text)
    except OSError as error:
        print(f"bin_to_header: cannot write {args.output}: {error.strerror}", file=sys.stderr)
        return 1
    print(f"bin_to_header: wrote {args.output} ({len(data)} bytes, "
          f"version word 0x{version_word(data):08X}, sha256 {hashlib.sha256(data).hexdigest()})",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
